import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(readFileSync(path.join(root, 'package-lock.json'), 'utf8'));

const compatible = new Set([
  'MIT',
  'MIT-0',
  'ISC',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'Apache-2.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'OFL-1.1',
  'GPL-3.0-only',
  'GPL-3.0-or-later',
  'LGPL-2.1-only',
  'LGPL-2.1-or-later',
  'LGPL-3.0-only',
  'LGPL-3.0-or-later',
  'MPL-2.0',
  'Zlib',
  'CC0-1.0',
  '(MIT OR GPL-3.0-or-later)',
  '(MIT AND Zlib)',
]);

const notices = [];
const problems = [];

for (const [key, info] of Object.entries(lock.packages)) {
  if (!key.startsWith('node_modules/') || info.dev) continue;
  const dir = path.join(root, key);
  const pkgPath = path.join(dir, 'package.json');
  if (!existsSync(pkgPath)) continue;
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const name = pkg.name || info.name || key.split('node_modules/').pop();
  const version = pkg.version || info.version || '';
  const license = normalizeLicense(pkg.license, dir);
  const copyright = copyrightOf(dir, pkg);
  if (!compatible.has(license)) problems.push(`${name}@${version}: ${license || 'unknown'}`);
  notices.push({ name, version, license: license || 'unknown', copyright });
}

notices.push({
  name: 'exceljs',
  version: '4.4.0',
  license: 'MIT',
  copyright: 'Copyright (c) 2014-2019 Guyon Roche',
});

notices.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

if (problems.length) {
  console.error('Licences that are not compatible with GPL-3.0:');
  for (const problem of problems) console.error(`  ${problem}`);
  process.exit(1);
}

const markdown = [
  '# Third-party notices',
  '',
  'Office is free software under the GNU General Public License, version 3 or any later version. The program as distributed includes HyperFormula, which is GPL-3.0-only, so the combined suite is distributed under GPL-3.0.',
  '',
  'The browser build of ExcelJS 4.4.0 (MIT) is vendored in `vendor/`. The Node packaging of that library depends on `unzipper`, which depends on `buffers`, a package with no licence. That tree is not installed and is not part of this program.',
  '',
  '| Package | Version | Licence | Copyright |',
  '| --- | --- | --- | --- |',
  ...notices.map((item) => `| ${item.name} | ${item.version} | ${item.license} | ${escapeCell(item.copyright)} |`),
  '',
].join('\n');

writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), markdown);
writeFileSync(path.join(root, 'src/legal/notices.ts'), `/** Generated by scripts/notices.mjs. Do not edit by hand. */\nexport interface ThirdPartyNotice {\n  name: string;\n  version: string;\n  license: string;\n  copyright: string;\n}\n\nexport const thirdPartyNotices: ThirdPartyNotice[] = ${JSON.stringify(notices, null, 2)};\n`);
console.log(`Wrote ${notices.length} third-party notices.`);

function normalizeLicense(value, dir) {
  const raw = Array.isArray(value) ? value.join(' OR ') : String(value ?? '').trim();
  if (raw === 'MIT*' || raw === 'MIT/X11' || raw === 'MIT OR X11') return 'MIT';
  if (raw === 'BSD' || raw === 'BSD*') {
    const text = licenseText(dir);
    if (/Redistributions of source code must retain/.test(text) && !/3\.\s/.test(text.slice(0, 800))) return 'BSD-2-Clause';
    if (/Neither the name/.test(text)) return 'BSD-3-Clause';
  }
  return raw;
}

function licenseText(dir) {
  for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'LICENCE', 'COPYING']) {
    const target = path.join(dir, file);
    if (existsSync(target)) return readFileSync(target, 'utf8').slice(0, 2000);
  }
  return '';
}

function copyrightOf(dir, pkg) {
  const text = licenseText(dir);
  const match = text.match(/Copyright[^\n]*/i);
  if (match) return match[0].replace(/\s+/g, ' ').trim();
  if (typeof pkg.author === 'string') return pkg.author;
  if (pkg.author && typeof pkg.author === 'object' && pkg.author.name) return String(pkg.author.name);
  return '';
}

function escapeCell(value) {
  return value.replace(/\|/g, '\\|');
}
